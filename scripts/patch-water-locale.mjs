const chinese = /[\u3400-\u9fff]/;
const literals = /"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'/g;
const source = await readFile(game, 'utf8');
const alreadyPatched = source.includes('window.WaterLocale.text(');
if (!alreadyPatched) assert.equal(createHash('sha256').update(source).digest('hex'), originalHash,
  'Game source changed; review the localization patch before rebuilding');
const found = new Set();
let occurrences = 0;
const output = source.replace(literals, (literal, offset) => {
  if (!chinese.test(literal)) return literal;
  const text = literal[0] === '"' ? JSON.parse(literal) : literal.slice(1, -1).replace(/\\'/g, "'");
  assert.ok(Object.hasOwn(translations, text), `Untranslated game string: ${text}`);
  found.add(text);
  occurrences++;
  if (alreadyPatched) {
    assert.ok(source.slice(Math.max(0, offset - 24), offset).endsWith('window.WaterLocale.text('),
      `Unwrapped game string: ${text}`);
    return literal;
  }
  return `window.WaterLocale.text(${literal})`;
});
assert.equal(found.size, Object.keys(translations).length, 'Unused or missing translations');
if (!alreadyPatched) await writeFile(game, output);

const helperSource = `// Generated by scripts/patch-water-locale.mjs.\n(() => {\n  'use strict';\n  const english = ${JSON.stringify(translations, null, 2)};\n  const language = () => window.PlaygroundI18n?.language || 'zh-CN';\n  const bootLanguage = language();\n  window.WaterLocale = {\n    text: value => language() === 'en' ? (english[value] ?? value) : value,\n    get language() { return bootLanguage; }\n  };\n  window.addEventListener('playground:languagechange', () => {\n    if (language() !== bootLanguage) {\n      location.replace(window.PlaygroundI18n.withLanguage(location.href));\n    }\n  });\n})();\n`;
await writeFile(helper, helperSource);
